create or replace view public.catalyst_dashboard_rows with (security_invoker=true) as
select cr.id as report_id,cr.report_type,cr.generated_at_sgt,cr.market_summary,cr.themes_summary,cr.best_focus,cr.output_version,
r.table_number,r.row_order,r.ticker,r.catalyst_event_date,r.catalyst_quality_direction,r.primary_catalyst_category,r.catalyst_tags,r.catalyst_summary,r.sector,r.theme,r.direct_sympathy_sector_move,r.sympathy_related_tickers,r.catalyst_release_session,r.reaction_date,r.move_already_done,r.volume_liquidity_confirmation,r.freshness_catalyst_age,r.source_confidence,r.primary_source_evidence,r.trade_read,r.risk_invalidator,r.action_priority,r.trading_date_checked
from public.catalyst_reports cr join public.catalyst_rows r on r.report_id=cr.id where r.table_number=3;
grant select on public.catalyst_dashboard_rows to authenticated;
