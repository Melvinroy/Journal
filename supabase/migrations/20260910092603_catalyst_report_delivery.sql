-- Preserve existing policies; bootstrap the optional feed for new installations.
do $$ begin
  if not exists(select 1 from pg_policies where tablename='catalyst_reports' and cmd='SELECT') then
    create policy "Authenticated users can read catalyst reports" on public.catalyst_reports for select to authenticated using(true);
  end if;
  if not exists(select 1 from pg_policies where tablename='catalyst_rows' and cmd='SELECT') then
    create policy "Authenticated users can read catalyst rows" on public.catalyst_rows for select to authenticated using(true);
  end if;
end $$;
grant select on public.catalyst_reports,public.catalyst_rows to authenticated;
grant all on public.catalyst_reports,public.catalyst_rows to service_role;
grant usage,select on sequence public.catalyst_rows_id_seq to service_role;

