create table public.catalyst_delivery_events (
  id bigint generated always as identity primary key,
  report_type text check(report_type in ('Premarket','Postmarket','Weekend Summary')),
  report_id uuid references public.catalyst_reports(id),
  stage text not null check(stage in ('scheduler','generation','ingestion','publication')),
  status text not null check(status in ('started','succeeded','failed')),
  observed_at timestamptz not null default now(),
  scheduled_for timestamptz,
  summary text check(summary in ('Report accepted','Duplicate delivery','Correction accepted','Invalid report payload','Revision conflict','Generation failed','Scheduler run failed','Scheduler run completed','Run started'))
);
alter table public.catalyst_delivery_events enable row level security;
create policy "Read catalyst delivery metadata" on public.catalyst_delivery_events for select to authenticated using(true);
grant select on public.catalyst_delivery_events to authenticated;
grant select,insert on public.catalyst_delivery_events to service_role;
grant usage,select on sequence public.catalyst_delivery_events_id_seq to service_role;
create view public.catalyst_delivery_status with (security_invoker=true) as
select distinct on(report_type,stage) report_type,stage,status,observed_at,scheduled_for,summary
from public.catalyst_delivery_events order by report_type,stage,observed_at desc,id desc;
grant select on public.catalyst_delivery_status to authenticated;

create or replace function public.ingest_catalyst_report(payload jsonb)
returns jsonb language plpgsql security invoker set search_path='' as $$
declare
  kind text; legacy_kind text; rid uuid; existing public.catalyst_reports;
  revision_number integer; expected_revision integer; item jsonb; row_value public.catalyst_rows;
  stored_payload jsonb; failure_summary text := 'Invalid report payload';
  report_date date; start_date date; end_date date; published timestamptz; generated timestamptz; scheduled timestamptz;
begin
  -- This inner transaction rolls back all report changes on any validation/constraint failure.
  begin
    kind:=payload->>'report_type';
    legacy_kind:=case kind when 'Premarket' then 'Premarket Catalyst Brief' when 'Postmarket' then 'After-Market Catalyst Brief' when 'Weekend Summary' then 'Weekend Catalyst Summary' end;
    if legacy_kind is null or jsonb_typeof(payload)<>'object'
      or jsonb_typeof(payload->'report_key') is distinct from 'string'
      or jsonb_typeof(payload->'source') is distinct from 'string'
      or coalesce(length(trim(payload->>'report_key')),0) not between 1 and 200
      or coalesce(length(trim(payload->>'source')),0) not between 1 and 200
      or payload->>'source' <> trim(payload->>'source')
      or payload->>'report_key' <> trim(payload->>'report_key')
      or jsonb_typeof(payload->'raw_report_text') is distinct from 'string'
      or coalesce(length(trim(payload->>'raw_report_text')),0) not between 1 and 2000000
      or coalesce(jsonb_typeof(payload->'rows'),'null')<>'array'
      or coalesce(payload->>'output_version','')<>'Catalyst_Table_v2'
      or coalesce(payload->>'revision','') !~ '^[1-9][0-9]*$'
      or coalesce(payload->>'expected_revision','') !~ '^[0-9]+$'
      or coalesce(payload->>'report_date','') !~ '^\d{4}-\d{2}-\d{2}$'
      or coalesce(payload->>'coverage_start','') !~ '^\d{4}-\d{2}-\d{2}$'
      or coalesce(payload->>'coverage_end','') !~ '^\d{4}-\d{2}-\d{2}$'
      or coalesce(payload->>'published_at','') !~ 'T.*(Z|[+-]\d{2}:\d{2})$'
      or coalesce(payload->>'generated_at','') !~ 'T.*(Z|[+-]\d{2}:\d{2})$'
    then raise exception 'Invalid report'; end if;
    if exists(select 1 from jsonb_each(payload) e where e.key in ('raw_report_text','coverage_window','market_session_focus','market_summary','themes_summary','best_focus') and jsonb_typeof(e.value) not in ('string','null')) then raise exception 'Invalid metadata'; end if;
    report_date:=(payload->>'report_date')::date;
    start_date:=(payload->>'coverage_start')::date; end_date:=(payload->>'coverage_end')::date;
    published:=(payload->>'published_at')::timestamptz; generated:=(payload->>'generated_at')::timestamptz;
    if start_date>end_date or generated>published or published>now()+interval '5 minutes' then raise exception 'Invalid dates'; end if;
    if payload->>'scheduled_for' is not null then
      if payload->>'scheduled_for' !~ 'T.*(Z|[+-]\d{2}:\d{2})$' then raise exception 'Invalid run time'; end if;
      scheduled:=(payload->>'scheduled_for')::timestamptz;
    end if;
    revision_number:=(payload->>'revision')::integer; expected_revision:=(payload->>'expected_revision')::integer;
    -- Serialize concurrent first deliveries and corrections of the same identity.
    perform pg_advisory_xact_lock(hashtextextended(concat_ws('|',kind,payload->>'source',payload->>'report_key'),0));
    select * into existing from public.catalyst_reports
      where report_type=legacy_kind and source=payload->>'source' and report_key=payload->>'report_key' for update;
    if existing.id is not null then
      select r.payload into stored_payload from public.catalyst_report_revisions r where r.report_id=existing.id and r.revision=revision_number;
      if stored_payload=payload then
        insert into public.catalyst_delivery_events(report_type,report_id,stage,status,scheduled_for,summary)
          values(kind,existing.id,'ingestion','succeeded',scheduled,'Duplicate delivery');
        return jsonb_build_object('status','duplicate','report_id',existing.id,'revision',revision_number);
      end if;
      if expected_revision<>existing.revision or revision_number<>existing.revision+1
        or report_date<>existing.trading_date_checked or published<existing.published_at then
        failure_summary:='Revision conflict';raise exception 'Conflict';
      end if;
      rid:=existing.id;
    elsif revision_number<>1 or expected_revision<>0 then
      failure_summary:='Revision conflict';raise exception 'Conflict';
    else rid:=gen_random_uuid();
    end if;
    if jsonb_array_length(payload->'rows')>3000 then raise exception 'Too many rows'; end if;
    insert into public.catalyst_reports(id,report_type,trading_date_checked,generated_at_sgt,coverage_window,output_version,market_summary,themes_summary,best_focus,report_key,source,coverage_start,coverage_end,published_at,scheduled_for,revision,result_count)
      values(rid,legacy_kind,report_date,generated,payload->>'coverage_window','Catalyst_Table_v2',payload->>'market_summary',payload->>'themes_summary',payload->>'best_focus',payload->>'report_key',payload->>'source',start_date,end_date,published,scheduled,revision_number,(select count(*) from jsonb_array_elements(payload->'rows') r where r->>'table_number'='3'))
      on conflict(id) do update set generated_at_sgt=excluded.generated_at_sgt,coverage_window=excluded.coverage_window,market_summary=excluded.market_summary,themes_summary=excluded.themes_summary,best_focus=excluded.best_focus,coverage_start=excluded.coverage_start,coverage_end=excluded.coverage_end,published_at=excluded.published_at,scheduled_for=excluded.scheduled_for,revision=excluded.revision,result_count=excluded.result_count;
    -- Earlier immutable payloads retain every row and metadata field from prior revisions.
    delete from public.catalyst_rows where report_id=rid;
    for item in select value from jsonb_array_elements(payload->'rows') loop
      if jsonb_typeof(item)<>'object' or item ? 'report_id' or item ? 'id' or item ? 'created_at'
        or coalesce(item->>'trading_date_checked','')<>report_date::text
        or coalesce(length(trim(item->>'ticker')),0)=0 then raise exception 'Invalid row'; end if;
      row_value:=jsonb_populate_record(null::public.catalyst_rows,item);
      insert into public.catalyst_rows(report_id,table_number,row_order,ticker,catalyst_event_date,catalyst_quality_direction,primary_catalyst_category,catalyst_tags,catalyst_summary,sector,theme,direct_sympathy_sector_move,sympathy_related_tickers,catalyst_release_session,reaction_date,move_already_done,volume_liquidity_confirmation,freshness_catalyst_age,source_confidence,primary_source_evidence,trade_read,risk_invalidator,action_priority,trading_date_checked)
      values(rid,row_value.table_number,row_value.row_order,row_value.ticker,row_value.catalyst_event_date,row_value.catalyst_quality_direction,row_value.primary_catalyst_category,row_value.catalyst_tags,row_value.catalyst_summary,row_value.sector,row_value.theme,row_value.direct_sympathy_sector_move,row_value.sympathy_related_tickers,row_value.catalyst_release_session,row_value.reaction_date,row_value.move_already_done,row_value.volume_liquidity_confirmation,row_value.freshness_catalyst_age,row_value.source_confidence,row_value.primary_source_evidence,row_value.trade_read,row_value.risk_invalidator,row_value.action_priority,row_value.trading_date_checked);
    end loop;
    if exists(select 1 from public.catalyst_rows r where r.report_id=rid and r.table_number in (1,2) and not exists(select 1 from public.catalyst_rows c where c.report_id=rid and c.table_number=3 and c.ticker=r.ticker)) then raise exception 'Table 3 incomplete'; end if;
    update public.catalyst_reports set
      last_received_at=now(),
      raw_report_text=payload->>'raw_report_text',market_session_focus=payload->>'market_session_focus',
      table_1_tickers=array(select ticker from public.catalyst_rows where report_id=rid and table_number=1 order by row_order),
      table_2_tickers=array(select ticker from public.catalyst_rows where report_id=rid and table_number=2 order by row_order),
      table_3_tickers=array(select ticker from public.catalyst_rows where report_id=rid and table_number=3 order by row_order)
    where id=rid;
    insert into public.catalyst_report_revisions(report_id,revision,payload) values(rid,revision_number,payload);
    insert into public.catalyst_delivery_events(report_type,report_id,stage,status,scheduled_for,summary)
      values(kind,rid,'ingestion','succeeded',scheduled,case when revision_number=1 then 'Report accepted' else 'Correction accepted' end),
            (kind,rid,'publication','succeeded',scheduled,'Report accepted');
    return jsonb_build_object('status',case when revision_number=1 then 'published' else 'corrected' end,'report_id',rid,'revision',revision_number);
  exception when others then
    insert into public.catalyst_delivery_events(report_type,stage,status,scheduled_for,summary)
      values(case when kind in ('Premarket','Postmarket','Weekend Summary') then kind end,'ingestion','failed',scheduled,failure_summary);
    return jsonb_build_object('status','rejected','error',failure_summary);
  end;
end $$;
revoke all on function public.ingest_catalyst_report(jsonb) from public,anon,authenticated;
grant execute on function public.ingest_catalyst_report(jsonb) to service_role;

