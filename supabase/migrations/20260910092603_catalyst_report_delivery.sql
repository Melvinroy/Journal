-- Captured schema shape from the existing optional Catalyst integration; no market data.
create table if not exists public.catalyst_reports (
  id uuid default gen_random_uuid() not null,
  report_type text not null,
  trading_date_checked date not null,
  generated_at_sgt timestamp with time zone not null,
  coverage_window text,
  market_session_focus text,
  output_version text default 'Catalyst_Table_v2'::text not null,
  market_summary text,
  themes_summary text,
  best_focus text,
  table_1_tickers text[] default '{}'::text[] not null,
  table_2_tickers text[] default '{}'::text[] not null,
  table_3_tickers text[] default '{}'::text[] not null,
  raw_report_text text,
  created_at timestamp with time zone default now() not null,
  constraint catalyst_reports_output_version_check CHECK ((output_version = 'Catalyst_Table_v2'::text)),
  constraint catalyst_reports_pkey PRIMARY KEY (id),
  constraint catalyst_reports_report_type_check CHECK ((report_type = ANY (ARRAY['Premarket Catalyst Brief'::text, 'After-Market Catalyst Brief'::text, 'Weekend Catalyst Summary'::text]))),
  constraint catalyst_reports_report_type_trading_date_checked_generated_key UNIQUE (report_type, trading_date_checked, generated_at_sgt)
);
alter table public.catalyst_reports enable row level security;
